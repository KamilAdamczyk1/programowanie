def month(number):
    result = int(number)
    month_name = ''
    if result == 1:
        month_name = 'January'
        return month_name
    elif result == 2:
        month_name = 'February'
        return month_name
    elif result == 3:
        month_name = 'March'
        return month_name
    elif result == 4:
        month_name = 'April'
        return month_name
    elif result == 5:
        month_name = 'May'
        return month_name
    elif result == 6:
        month_name = 'June'
        return month_name
    elif result == 7:
        month_name = 'July'
        return month_name
    elif result == 8:
        month_name = 'August'
        return month_name
    elif result == 9:
        month_name = 'September'
        return month_name
    elif result == 10:
        month_name = 'October'
        return month_name
    elif result == 11:
        month_name = 'November'
        return month_name
    elif result == 12:
        month_name = 'December'
        return month_name